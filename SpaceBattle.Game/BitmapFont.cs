namespace SpaceBattle.Game;

internal static class BitmapFont
{
    private static readonly Dictionary<char, byte[]> Glyphs = new();
    static BitmapFont()
    {
        const string chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .:-/+%()[]?";
        string[] patterns = [
            "0E11111F111111","1E11111E11111E","0F10101010100F","1E11111111111E","1F10101E10101F","1F10101E101010","0F10101711110F","1111111F111111","0E04040404040E","0702020212120C","11121418141211","1010101010101F","111B1515111111","11191513111111","0E11111111110E","1E11111E101010","0E11111115120D","1E11111E141211","0F10100E01011E","1F040404040404","1111111111110E","11111111110A04","11111115151B11","11110A040A1111","11110A04040404","1F01020408101F",
            "0E11131519110E","040C040404040E","0E11010204081F","1E01010E01011E","02060A121F0202","1F10101E01011E","0E10101E11110E","1F010204080808","0E11110E11110E","0E11110F01010E",
            "00000000000000","00000000000C0C","000C0C000C0C00","0000001F000000","01010204080810","0004041F040400","19190204081313","02040808080402","08040202020408","0E08080808080E","0E02020202020E","0E110102040004"
        ];
        for(int i=0;i<chars.Length;i++) Glyphs[chars[i]]=Enumerable.Range(0,7).Select(r=>Convert.ToByte(patterns[i].Substring(r*2,2),16)).ToArray();
    }
    public static byte[] Get(char c) => Glyphs.TryGetValue(c,out var g)?g:Glyphs['?'];
}
